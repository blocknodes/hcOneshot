"""一把出 prompt：单次 LLM 产出 [{q, d, tool, params}]。

与 hcSlime 的 T0（hcAgent/app/prompts.py）同源改写：
  保留 —— 域判别要点、拆单规则、改写要求（这些在线上已验证有效）；
  改动 —— T0 的「不选工具，交下游 hcTools」改为「同时选工具并填参」；
         追加参数块（精简目录，见 catalog.render_oneshot_block）。
"""
from __future__ import annotations

# 基础 prompt：任务 + 输出契约 + 域判别 + 规则。参数块与锚例在 build_oneshot_prompt 里追加。
ONESHOT_PROMPT = """你是电视语音助手。读用户请求，**一次性**给出执行计划：拆句、改写、定域、选工具、填参数。

【输出】顶层 JSON 数组，每一项是一条计划，只输出数组本身，不要 ``` 解释、不要 thinking：
[{"q": <改写后自包含子请求>, "d": <域>, "tool": <工具名>, "params": <参数对象>, "dep": <可选,所依赖条序号>}]

字段规则：
- "q": 改写后【自包含、可直接执行】的一句话子请求；保留用户核心意图动词（"听"不可改成"播放"）。
- "d": 域，取值之一：vod / children / education / music / audio / sports / device（只有这 7 个）；
  无法归入任何域（通用知识问答/闲聊）时**不写 d**，由系统走通用兜底。
- "tool": 该域下选定的工具名，**只能取下方目录里列出的**；拿不准就选该域最通用的检索工具。
  目录里写作 `域:工具`（如 `vod:vod_search_all`），"tool" 只填【冒号后半段】（填 `vod_search_all`）。
- "params": 该工具的参数对象，**按下方目录给出的参数名与类型填**；只抽用户明确表达的信息，
  不臆造；用户没提的可选字段不要出现（不要填 null / 空串 / 空数组）。
- "dep": 仅当该条依赖【更早一条】的结果（如"该导演的影片""第三个""评分最高的一部"）才用，
  值=所依赖条的序号（从 1 计数）；并行独立条目不写。

【域判别——按内容本质选域，别只看"视频/播放"就归 vod】：
- sports：比赛/赛事/锦标赛/决赛/预选赛/录像集锦/比分/赛程/球队排名/网球/跳水/格斗/足球/篮球/NBA/搏击。
- children：面向孩子/儿童/宝宝/幼儿 的教学、启蒙、绘本、卡通、动漫、动画内容。
- music：歌曲/歌手/歌词/点歌/K歌/歌单/音乐/MV（"XX的歌视频/MV"仍是 music）。
- education：年级/科目(语文数学英语物理…)/教材/同步课/人教版/课程 等课堂教育。
- audio：用户**主动要听**的听书/音频——"听/想听/请听/要听/听听 X"（书/评书/广播剧/有声小说/故事/章节），
  以及 我听过的/收听记录/音频/有声书/广播剧/睡前听书。
- vod：以上均不命中的人民影视剧/电影/电视剧/纪录片，或泛泛的"播放XX片"（只有"看/播放+视频"才归 vod）。
- device：设备控制（音量/亮度/开关机/定时/模式…）。

【拆单规则】：
1. 每个 q 只属一个域；多个独立目标（"播放战狼2同时调大音量"）必须全部拆出，不准丢。
2. 并列属性不拆：同一检索里的并列条件（"数学和语文""上册和下册""三年级和四年级"）属于【单个检索】，
   只输出一条，让参数里表达并列；只有真正独立的动作才拆。
3. 单目标就只输出一条。纯聊天/问候（"你好""在吗"）→ 输出空数组 []。
   注意：推荐/给我推荐/按我喜好推荐是【检索动作，非纯聊天】，必须拆出并落到对应内容域。
4. 【排序/筛选修饰归属】：用户在第一句就带排序/筛选修饰（"评分最高的/人气最高的/最新的一部/播放量最高"）时，
   该修饰**属于第一句检索**，必须保留在第一句 q 与其 params 里，**严禁**下放成第二句对结果的二次筛选。
   第二句只保留对结果的属性提问（"这一部的导演是谁"），并用 dep 指向第一句。

【工具与参数目录】
__TOOLS__
"""

# 虚拟工具目录段（与 T0 的 _VTOOL_HEADER 同源）。
_TOOL_HEADER = """
__TOOLS__
"""

# 锚例：仅定格式。参数形态按目录里的参数名来填。
_ANCHORS = """
【锚例（仅定格式，内容不要照抄）】
用户：2020年之后拍的电影
[{"q":"搜索2020年之后上映的电影","d":"vod","tool":"vod_search_all","params":{"action":"search","retext":"搜索2020年之后上映的电影","query":{"and":[{"field":"release_time","from":"20200101","to":"*"},{"field":"category","value":"电影"}]}}}]

用户：播放战狼2，顺便把音量调到30
[{"q":"播放战狼2","d":"vod","tool":"vod_search_all","params":{"action":"play","retext":"播放战狼2","query":{"field":"title","value":"战狼2"}}},
 {"q":"把音量调到30","d":"device","tool":"numeric_adjust","params":{"object":"volume","value":"30"}}]

用户：搜索评分最高的胡歌演的电影，导演是谁
[{"q":"搜索评分最高的胡歌演的电影","d":"vod","tool":"vod_search_all","params":{"action":"search","retext":"搜索评分最高的胡歌演的电影","query":{"and":[{"field":"actor","value":"胡歌"},{"field":"category","value":"电影"}],"operator":"and"}},"sort":{"rate":{"order":"desc"}}},
 {"q":"这一部电影的导演是谁","d":"vod","tool":"fan_knowledge_agent","params":{"messages":"这部电影的导演是谁"},"dep":1}]

用户：你好
[]
"""


def build_oneshot_prompt(catalog_block: str = "") -> str:
    """一把出 system prompt：目录块非空时注入工具+参数目录，并追加锚例。"""
    base = ONESHOT_PROMPT
    if catalog_block:
        base = base.replace("__TOOLS__", catalog_block)
    else:
        # 目录为空（hcTools 未起/拉取失败）：仍可拆句定域，工具与参数留空由下游兜底。
        base = base.replace("【工具与参数目录】\n__TOOLS__\n",
                            "【工具与参数目录】（当前不可用：只填 q 与 d，tool/params 留空）\n")
    return base + _ANCHORS


# T1 续跑：把【待执行意图】用上一步真实结果改写成自包含 query，并**同时**给出 tool+params。
# 与 hcAgent 的 T1_STEP_PROMPT 同源（只把指代换成具体实体、保留问句主体），
# 差异：hcAgent 的 T1 只输出改写后 query，工具与参数交 hcTools；hcOneshot 无 hcTools 跳，
# 故 T1 一并输出该步的 tool+params（单次调用完成"改写+填参"）。
T1_STEP_PROMPT = """你是电视语音助手。上一步工具结果已给出具体实体(片名/人名/比赛等)。
把下面这条【待办意图】改写成【自包含、无指代、可直接执行】的一句话，并给出该步要用的工具与参数，
只输出一个 JSON 对象，不要 ``` 说明、不要 thinking。

改写要求（与首轮同源）：
- 只把 指代/相对最高最低/第N部 等换成工具结果里出现过的一个具体实体；其余部分（要问的属性）一字不改保留。
- 例："评分最高的一部导演是谁" → "《无间道》的导演是谁"（保留"的导演是谁"）。
- 严禁压缩：不得把整个问句缩成一个孤立片名（如只输出"功夫"）；改写后必须仍是完整的可问句。

工具与参数：从下方目录里选该步的工具（只能取目录列出的），并按目录参数名与类型填 params；
只抽已明确的信息，不臆造；用户没提的可选字段不要出现。
属性提问/知识问答（"XX的导演是谁""为什么…"）通常对应各域的 fan_knowledge_agent。

输出格式（单个对象）：
{"q": <改写后自包含句>, "tool": <工具名>, "params": <参数对象>}

【工具与参数目录】
__TOOLS__

锚（仅定格式）：
待办意图:查询搜索结果中第三部的导演是谁
工具结果:候选媒资(按搜索排位):\n第1部: 《功夫》 导演:周星驰 评分:7.8 ...\n第2部: 《美人鱼》 导演:周星驰 ...\n第3部: 《西游降魔篇》 导演:周星驰 ...
{"q":"《西游降魔篇》的导演是谁","tool":"fan_knowledge_agent","params":{"messages":"《西游降魔篇》的导演是谁"}}
"""


def build_t1_prompt(catalog_block: str = "") -> str:
    """T1 续跑 system prompt：注入（同 T0 的）目录块，使续跑也一次出 tool+params。"""
    if catalog_block:
        return T1_STEP_PROMPT.replace("__TOOLS__", catalog_block)
    return T1_STEP_PROMPT.replace(
        "【工具与参数目录】\n__TOOLS__",
        "【工具与参数目录】（当前不可用：tool 留空，由下游兜底）")


# 多轮改写：把「本轮请求 + 跨轮对话历史」合并成自包含 query。
# 逐字节移植自 hcAgent/app/prompts.py::MT_REWRITE_PROMPT（线上已验证有效；勿手改措辞，
# 词表/锚例任何漂移都会静默改变改写行为——需要时整体同步，不局部润色）。
# 与 hcAgent 的唯一差别：这里只输出【改写后的 query 文本】（一把出无需在此选工具/填参，
# 后续仍走 T0 计划；hcAgent 亦仅输出 query 文本）。
MT_REWRITE_PROMPT = """你是电视语音助手。下面是同一设备近来的【对话历史】（用户请求 query + 助手应答 answer），以及【本轮新的用户请求】。
把本轮请求补全历史上下文，改写成【自含、完整、可直接执行】的【检索意图序列】。

【最关键意图结构约束——禁止压扁多意图】：
- 本轮请求可能同时含【多个意图】，且常是串行依赖（如“它导演是谁？他导过的电影”→ 先问导演、再找该导演的电影）。你必须全部保留、一句一意图，**用英文分号 `;` 分隔**，严禁压缩合并成单个意图。
- 例：“《动物城2》的导演是谁；该导演导过的电影”。若意图本就自含单句，只输出这一句。
- 各意句指代处理遵照「单句规则」。

单句规则：
- 仅继承与本轮相关的历史上下文（内容类型、导演/主演、标签、语言、时间、排序等条件，或上一轮确定的某个具体内容）；
- 保留用户本来的诉求框架，不要擅自改变意图性质：用户只说“想看/看/有没有 悬疑的”（类型点播）时，改写成“想看悬疑电影/比赛”这类类型检索，【不要改成“推荐悬疑”】；“推荐/给我推荐/按我喜好推荐”才算推荐诉求；
- 【歌曲名锚点】当历史应答中出现【歌曲名】（如《吉量》、某歌手演唱的某首歌）时，把“这个歌/这首歌/刚才那首/那一首/它”这类指代还原成具体歌名后，**必须保留“歌/歌曲/听”字样的类别锚**：写成“播放《歌名》这首歌”“播放歌曲《歌名》”“我想听《歌名》”等形式，**严禁压成裸的“播放《歌名》”**。这能让下游（判域/选工具）识别这是歌曲域而非影视剧——裸书名号在无“歌曲/音乐”字样时会被误判成影视剧。“播放《X》”→“播放《X》这首歌”。
- 每句把历史里的具体内容/序号（如“第2首”“刚才那部”“网上那部”）时，把它替换/还原成历史 answer 里已确定的实际内容名；
- 【人物属性指代——优先还原人名】当本轮在问某【人】的属性（“该导演老婆”“他的妻子”“这位主演叫什么/还演过什么”“导演是谁”）时，把“该导演/这位导演/他/它”替换成历史候选里那个人的【具体人名】（直接取候选里的 director / actor 字段原文，如“杰拉德·布什”），**不要还原成带修饰词的片名**（绝不带“（普通话版）”这类后缀）。这样才能让下游对“导演老婆/XX演过”做正确的知识问答或检索。
- 【串行依赖句】若第 2+ 句指代第 1 句的结果（如“他/该导演/该导过的电影”“评分最高的一部”“第三个”），**保留指代与动作**，让下游识别串行依赖——不要改写成一个孤立片名、不要提前解析成具体内容；
- 【要点】若本轮是“第X部呢/那位呢/刚才那部呢/另一个呢”这类【承接上一条疑问】的省略，且上一轮是在问某个属性（导演是谁/主演是谁/评分多少/什么时候上映），则输出“《上轮已确定的第X部内容名》的<上一轮疑问属性>是什么”的完整疑问句，不要只输出片名、不要改成点播/检索，且只保留这一句（不额外加串行第二句）。
- 若本轮与历史无关（全新内容、切换业务），直接用本轮原句，不要勉强拼历史；
- 只输出改写后的 query 文本；多句用分号 `;` 分隔（无多余分隔、无结尾分号）；不要 markdown、不要 JSON、不要 thinking、不要书名号。
对话历史：
{dialog}
本轮用户请求：{cur_query}
若意图本就自含，原样输出即可。"""
